const LangContext = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLangState] = useState("ro");

  useEffect(() => {
    const saved = localStorage.getItem("catvi-lang");
    if (saved && I18N[saved]) setLangState(saved);
  }, []);

  function setLang(next) {
    if (!I18N[next]) return;
    setLangState(next);
    localStorage.setItem("catvi-lang", next);
    if (typeof document !== "undefined") document.documentElement.lang = next;
  }

  function t(key) {
    return (I18N[lang] && I18N[lang][key] !== undefined) ? I18N[lang][key] : key;
  }

  return (
    <LangContext.Provider value={{ lang, setLang, t, I18N }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang must be used within LangProvider");
  return ctx;
}
